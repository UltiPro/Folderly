password_regex = r"^[^\x00-\x1f\x7f]{8,40}$"
password_regex_desc = "Password must be between 8 and 40 characters long."
segment_regex = r"[^/\\<>:\"|?*\x00-\x1f.]"
path_regex = rf"^(/{segment_regex}+)*(/)?$"
path_regex_error = "Invalid path."
folder_regex = rf"^{segment_regex}+$"
folder_regex_error = "Invalid folder name. A folder name cannot contain a dot, a slash or any of < > : \" | ? *."
file_regex = r"^(?!\.+$)[a-zA-Z0-9_.-]+$"
file_regex_error = "Invalid file name. File names can only contain letters, digits, dots (.), dashes (-) and underscores (_), and can't consist of only dots."
